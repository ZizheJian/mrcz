data=np.array([int(x) for x in str.split()]).reshape((10,10,10))

def cube_mesh(x,y,z,size=1.0):
    v = np.array([
        [x, y, z],
        [x+size, y, z],
        [x+size, y+size, z],
        [x, y+size, z],
        [x, y, z+size],
        [x+size, y, z+size],
        [x+size, y+size, z+size],
        [x, y+size, z+size]
    ])

    # 三角面索引
    faces = np.array([
        [0,1,2], [0,2,3],  # bottom
        [4,5,6], [4,6,7],  # top
        [0,1,5], [0,5,4],
        [2,3,7], [2,7,6],
        [1,2,6], [1,6,5],
        [0,3,7], [0,7,4]
    ])

    return v, faces

fig = go.Figure()

# 颜色定义
color_one = "rgb(220,235,250)"  # 非常浅的蓝色
color_zero = "darkred"

for i in range(10):
    for j in range(10):
        for k in range(10):
            v, f = cube_mesh(i, j, k)
            fig.add_trace(
                go.Mesh3d(
                    x=v[:,0],
                    y=v[:,1],
                    z=v[:,2],
                    i=f[:,0],
                    j=f[:,1],
                    k=f[:,2],
                    color=color_one if data[i,j,k] == 1 else color_zero,
                    opacity=0.05 if data[i,j,k] == 1 else 1,
                    flatshading=True,
                    showscale=False
                )
            )

fig.update_layout(
    scene=dict(
        xaxis=dict(visible=False),
        yaxis=dict(visible=False),
        zaxis=dict(visible=False),
        aspectmode="cube"
    ),
    margin=dict(l=0, r=0, b=0, t=0)
)

fig.write_html("fig/zero_map.html")